export type ImportCopyKey = keyof typeof copy.rw;

export const getImportCopy = (language: PublicLanguage, key: ImportCopyKey, params?: Record<string, string | number>) => {
  let text: string = copy[language][key] || copy.rw[key] || key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value));
    }
  }
  return text;
};
