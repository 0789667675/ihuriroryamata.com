export type PublicLanguage = keyof typeof publicCopy;
export type PublicCopyKey = keyof typeof publicCopy.rw;

export const normalizePublicLanguage = (
  value: string | null | undefined
): PublicLanguage => value === 'en' ? 'en' : 'rw';

/**
 * Render a copy key stored inside a notification `details` payload. Falls back to
 * the persisted (Kinyarwanda) text when no key is present, so legacy notifications
 * keep working, and replaces `{param}` placeholders from the stored parameters.
 */
export const formatPublicCopy = (
  language: PublicLanguage,
  key: string | null | undefined,
  fallback: string,
  params: Record<string, string | number> = {}
): string => {
  const dictionary = publicCopy[language] as Record<string, string>;
  const template = key && typeof dictionary[key] === 'string' ? dictionary[key] : fallback;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value ?? '')),
    template
  );
};